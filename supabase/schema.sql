create table if not exists public.club_signups (
    id bigint generated by default as identity primary key,
    local_id bigint unique,
    student_id text not null,
    student_name text not null,
    club_name text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.club_members (
    user_id uuid primary key references auth.users (id) on delete cascade,
    access_level text not null check (access_level in ('viewer', 'editor')),
    granted_at timestamptz not null default now()
);

create table if not exists public.club_owners (
    user_id uuid primary key references auth.users (id) on delete cascade,
    created_at timestamptz not null default now()
);

alter table public.club_signups enable row level security;
alter table public.club_members enable row level security;
alter table public.club_owners enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.club_signups to authenticated;
grant usage, select on sequence public.club_signups_id_seq to authenticated;
revoke all on public.club_signups from anon;
revoke all on public.club_members, public.club_owners
    from anon, authenticated;
grant select on public.club_members, public.club_owners to authenticated;

drop policy if exists "Authenticated users can view sign-ups"
    on public.club_signups;
create policy "Authenticated users can view sign-ups"
    on public.club_signups for select to authenticated
    using (
        exists (
            select 1 from public.club_members
            where user_id = (select auth.uid())
        )
        or exists (
            select 1 from public.club_owners
            where user_id = (select auth.uid())
        )
    );

drop policy if exists "Editors and owners can insert sign-ups"
    on public.club_signups;
create policy "Editors and owners can insert sign-ups"
    on public.club_signups for insert to authenticated
    with check (
        exists (
            select 1 from public.club_members
            where user_id = (select auth.uid())
              and access_level = 'editor'
        )
        or exists (
            select 1 from public.club_owners
            where user_id = (select auth.uid())
        )
    );

drop policy if exists "Editors and owners can update sign-ups"
    on public.club_signups;
create policy "Editors and owners can update sign-ups"
    on public.club_signups for update to authenticated
    using (
        exists (
            select 1 from public.club_members
            where user_id = (select auth.uid())
              and access_level = 'editor'
        )
        or exists (
            select 1 from public.club_owners
            where user_id = (select auth.uid())
        )
    )
    with check (
        exists (
            select 1 from public.club_members
            where user_id = (select auth.uid())
              and access_level = 'editor'
        )
        or exists (
            select 1 from public.club_owners
            where user_id = (select auth.uid())
        )
    );

drop policy if exists "Editors and owners can delete sign-ups"
    on public.club_signups;
create policy "Editors and owners can delete sign-ups"
    on public.club_signups for delete to authenticated
    using (
        exists (
            select 1 from public.club_members
            where user_id = (select auth.uid())
              and access_level = 'editor'
        )
        or exists (
            select 1 from public.club_owners
            where user_id = (select auth.uid())
        )
    );

drop policy if exists "Users can view their own club access"
    on public.club_members;
create policy "Users can view their own club access"
    on public.club_members for select to authenticated
    using (
        user_id = (select auth.uid())
        or exists (
            select 1 from public.club_owners
            where user_id = (select auth.uid())
        )
    );

drop policy if exists "Owners can view their own owner record"
    on public.club_owners;
create policy "Owners can view their own owner record"
    on public.club_owners for select to authenticated
    using (user_id = (select auth.uid()));

create or replace function public.set_club_access(
    member_email text,
    requested_access text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    target_user_id uuid;
begin
    if (select auth.uid()) is null
       or not exists (
           select 1 from public.club_owners
           where user_id = (select auth.uid())
       ) then
        raise exception 'Only a club owner can manage access';
    end if;

    if member_email is null or btrim(member_email) = '' then
        raise exception 'An account email is required';
    end if;

    if requested_access is null
       or requested_access not in ('viewer', 'editor', 'none') then
        raise exception 'Permission must be viewer, editor, or none';
    end if;

    select id into target_user_id
    from auth.users
    where lower(email) = lower(btrim(member_email))
    limit 1;

    if target_user_id is null then
        raise exception 'No account exists for that email';
    end if;

    if exists (
        select 1 from public.club_owners where user_id = target_user_id
    ) then
        raise exception 'Owner access cannot be changed here';
    end if;

    if requested_access = 'none' then
        delete from public.club_members
        where user_id = target_user_id;
    else
        insert into public.club_members (user_id, access_level)
        values (target_user_id, requested_access)
        on conflict (user_id) do update
        set access_level = excluded.access_level;
    end if;
end;
$$;

revoke all on function public.set_club_access(text, text) from public, anon;
grant execute on function public.set_club_access(text, text) to authenticated;
